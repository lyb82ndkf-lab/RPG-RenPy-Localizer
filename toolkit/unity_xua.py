"""Unity runtime bridge inspired by XUnity.AutoTranslator.

XUA already solves in-process text hooks (UGUI / TMP / NGUI / IMGUI / TextAsset).
We do not reimplement those hooks. Instead we:

1. Write XUA-compatible translation dictionaries (``original=translation``).
2. Generate an XUA / BepInEx install layout with ``Endpoint=CustomTranslate``
   pointing at a local HTTP endpoint.
3. Serve that CustomTranslate API (``GET ?from=&to=&text=`` → plain string)
   and optionally capture untranslated strings for the workbench.

Reference: ``其他/XUnity.AutoTranslator-master`` (MIT).
"""

from __future__ import annotations

import json
import re
import threading
import urllib.parse
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

from .models import ProjectInfo, TranslationEntry

# XUA CustomTranslate-style live port (distinct from Ren'Py 32180 / RM 32181 / Wolf WS 35421).
XUA_LIVE_PORT = 32182

XUA_TRANSLATION_REL = Path("AutoTranslator") / "Translation" / "zh-CN" / "Text"
XUA_MANUAL_FILE = "RPGRenPyLocalizer.txt"
XUA_AUTO_FILE = "_AutoGeneratedTranslations.txt"

_COMMENT_RE = re.compile(r"^\s*(//|#|;)")


def encode_xua_text(text: str) -> str:
    """Escape a single side of an XUA ``key=value`` line (TextHelper.Encode)."""
    out = (text or "").replace("\\", "\\\\")
    out = out.replace("=", "\\=")
    return out.replace("\r", "\\r").replace("\n", "\\n")


def decode_xua_segment(text: str) -> str:
    if text is None:
        return ""
    out: list[str] = []
    i = 0
    n = len(text)
    while i < n:
        ch = text[i]
        if ch != "\\":
            out.append(ch)
            i += 1
            continue
        i += 1
        if i >= n:
            out.append("\\")
            break
        esc = text[i]
        if esc in ("=", "\\"):
            out.append(esc)
        elif esc == "n":
            out.append("\n")
        elif esc == "r":
            out.append("\r")
        elif esc == "u" and i + 4 < n:
            try:
                out.append(chr(int(text[i + 1 : i + 5], 16)))
                i += 4
            except ValueError:
                out.append("\\u")
        else:
            out.append("\\")
            out.append(esc)
        i += 1
    return "".join(out)


def parse_xua_line(line: str) -> tuple[str, str] | None:
    """Parse one XUA translation line into (source, target). Returns None for junk."""
    raw = (line or "").strip("\r\n")
    if not raw.strip() or _COMMENT_RE.match(raw):
        return None
    parts: list[str] = []
    buf: list[str] = []
    i = 0
    n = len(raw)
    while i < n:
        ch = raw[i]
        if ch == "\\" and i + 1 < n:
            buf.append(ch)
            buf.append(raw[i + 1])
            i += 2
            continue
        if ch == "=":
            parts.append("".join(buf))
            buf = []
            i += 1
            continue
        buf.append(ch)
        i += 1
    parts.append("".join(buf))
    if len(parts) < 2:
        return None
    source = decode_xua_segment(parts[0])
    target = decode_xua_segment(parts[1])
    if not source.strip():
        return None
    return source, target


def format_xua_line(source: str, target: str) -> str:
    return f"{encode_xua_text(source)}={encode_xua_text(target)}"


def read_xua_translation_file(path: Path) -> list[tuple[str, str]]:
    if not path.is_file():
        return []
    text = path.read_text(encoding="utf-8-sig", errors="replace")
    pairs: list[tuple[str, str]] = []
    for line in text.splitlines():
        parsed = parse_xua_line(line)
        if parsed:
            pairs.append(parsed)
    return pairs


def write_xua_translation_file(path: Path, pairs: list[tuple[str, str]]) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "// Auto-generated by RPGRenPyLocalizer (XUA format).",
        "// Reload in-game with XUA ALT+R after editing.",
        "",
    ]
    for source, target in pairs:
        if source.strip() and target.strip() and source != target:
            lines.append(format_xua_line(source, target))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return path


def export_entries_to_xua(entries: list[TranslationEntry] | dict[str, TranslationEntry], target: Path) -> Path:
    values = list(entries.values()) if isinstance(entries, dict) else list(entries)
    pairs = [
        (entry.source, entry.target)
        for entry in values
        if entry.source.strip() and entry.target.strip() and entry.source != entry.target
    ]
    return write_xua_translation_file(target, pairs)


def import_xua_to_entries(path: Path, category: str = "unity_xua") -> list[TranslationEntry]:
    entries: list[TranslationEntry] = []
    for index, (source, target) in enumerate(read_xua_translation_file(path)):
        entries.append(
            TranslationEntry(
                entry_id=f"unity_xua::{path.name}::{index}",
                source=source,
                target=target,
                file=path.name,
                context=f"unity-xua;file={urllib.parse.quote(path.name, safe='')};row={index}",
                category=category,
            )
        )
    return entries


def build_xua_config(
    translate_url: str,
    from_language: str = "ja",
    to_language: str = "zh-CN",
    enable_imgui: bool = True,
    text_getter_compat: bool = True,
) -> str:
    """XUA Config.ini body wired to CustomTranslate (local RPGRenPyLocalizer)."""
    return (
        "[General]\n"
        "Endpoint=CustomTranslate\n"
        "FallbackEndpoint=\n"
        f"Language={to_language}\n"
        f"FromLanguage={from_language}\n"
        "HandleRichText=True\n"
        "IgnoreWhitespaceInDialogue=True\n"
        "SaveTextBetweenChunks=True\n"
        "RedirectedResourceOutputPath=ResourceRedirected\n"
        "TextureDirectory=Textures\n"
        "TextureHashGenerationStrategy=FromImageData\n"
        "EnableUIResizing=False\n"
        "EnableIMGUI=%s\n"
        "TextGetterCompatibilityMode=%s\n"
        "GeneratePartialTranslations=False\n"
        "AutoGenerateTranslations=True\n"
        "OutputFile=Translation\\{Lang}\\Text\\_AutoGeneratedTranslations.txt\n"
        "\n"
        "[Custom]\n"
        "Url=%s\n"
        "EnableShortDelay=True\n"
        "DisableSpamChecks=True\n"
        "\n"
        "[Http]\n"
        "UserAgent=\n"
        "DisableCertificateValidation=True\n"
        "\n"
        "[Behaviour]\n"
        "ForceMonoModHooks=False\n"
        "IgnoreResourceLoadingErrors=True\n"
        % (
            "True" if enable_imgui else "False",
            "True" if text_getter_compat else "False",
            translate_url.rstrip("?"),
        )
    )


